import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

const root = fileURLToPath(new URL("../", import.meta.url));
const text = z.string().trim().min(1);
const httpsUrl = text.refine((value) => URL.canParse(value) && new URL(value).protocol === "https:", "必须为 HTTPS URL");
const asset = text.regex(/^\/[\w./@-]+$/);
const filename = text.regex(/^[\w.-]+$/);
const color = text.regex(/^#[\da-f]{6}$/i);
const schema = z.strictObject({
  apiVersion: z.literal(1),
  id: text.regex(/^[a-z][a-z0-9-]*$/),
  productName: text,
  displayName: text,
  /** 侧栏主标题下的小字；品牌主副标题相同时填 null，界面只显示一行 */
  subtitle: text.nullable(),
  assistantName: text,
  slogan: text,
  author: text,
  web: z.strictObject({
    favicon: asset,
    mark: asset,
    monochromeMark: z.boolean(),
    themeColor: color,
    lightThemeColor: color,
    darkThemeColor: color,
    lightGradient: text,
    darkGradient: text,
    /**
     * 主色（按钮、链接、选中态）。null 表示沿用黑白骨架。
     * 深色主题单独给一组，因为亮色强调色在深底上会失去对比度。
     */
    accent: z.strictObject({
      light: color,
      dark: color,
      lightContrast: color,
      darkContrast: color,
    }).nullable(),
  }),
  desktop: z.strictObject({
    identifier: text.regex(/^[a-z0-9-]+(?:\.[a-z0-9-]+)+$/),
    backendPort: z.number().int().min(1024).max(65535),
    icons: z.array(text).min(1),
    updater: z.strictObject({
      pubkey: text,
      endpoints: z.array(httpsUrl).min(1),
      releasesUrl: httpsUrl,
      signingKeyFile: filename,
      changelog: text,
    }),
  }),
  provider: z.strictObject({
    name: text,
    baseUrl: httpsUrl,
    logo: asset,
    loginUrl: httpsUrl,
    keyUrl: httpsUrl.nullable(),
    supportQr: asset.nullable(),
    uploadEndpoint: httpsUrl,
    referenceImageUploadOrigins: z.array(httpsUrl.refine((url) => new URL(url).origin === url, "必须为不含路径的 origin")),
  }),
  support: z.strictObject({ authorEmail: z.email().nullable() }),
  wpsAddonId: text.regex(/^[A-Za-z][\w-]*$/),
});

export function readBrand(id = process.env.CHATCANVAS_BRAND || "chatcanvas") {
  if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error(`无效的品牌 ID：${id}`);
  const file = path.join(root, "brands", id, "brand.json");
  const brand = schema.parse(JSON.parse(fs.readFileSync(file, "utf8")));
  if (brand.id !== id) throw new Error(`品牌配置中的 id 与目录不符：${file}`);
  if (id !== "chatcanvas") {
    const main = readBrand("chatcanvas");
    if (brand.desktop.backendPort === main.desktop.backendPort || brand.desktop.identifier === main.desktop.identifier) {
      throw new Error("独立品牌必须同时设定不同于主版的后端端口和安装标识");
    }
  }
  return brand;
}

function writeGenerated(relativePath, contents) {
  const file = path.join(root, relativePath);
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === contents) return;
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, contents);
  fs.renameSync(tmp, file);
}

export function desktopBrandConfig(brand) {
  const base = JSON.parse(fs.readFileSync(path.join(root, "src-tauri", "tauri.conf.json"), "utf8"));
  const { identifier, backendPort, icons, updater } = brand.desktop;
  return {
    productName: brand.productName,
    identifier,
    app: {
      windows: base.app.windows.map((window) => ({ ...window, title: brand.productName })),
      security: {
        csp: base.app.security.csp.replaceAll(/http:\/\/127\.0\.0\.1:\d+/g, `http://127.0.0.1:${backendPort}`),
      },
    },
    bundle: { icon: icons },
    plugins: { updater: { pubkey: updater.pubkey, endpoints: updater.endpoints } },
  };
}

const configPath = path.join(root, "src-tauri", "tauri.brand.generated.json");

export function prepareBrand(brand = readBrand()) {
  const { id, provider, support, web, desktop, productName, displayName, subtitle, assistantName, slogan, author, wpsAddonId } = brand;
  const runtime = {
    id, productName, displayName, subtitle, assistantName, slogan, author, wpsAddonId, web, provider, support,
    backendPort: desktop.backendPort,
    releasesUrl: desktop.updater.releasesUrl,
  };
  // Keep nullable fields typed for brand packages that intentionally omit them.
  const generated = `// Generated by scripts/brand.mjs. Edit the brand profile instead.
const data = ${JSON.stringify(runtime, null, 2)};
export const BRAND = {
  ...data,
  subtitle: data.subtitle as string | null,
  web: {
    ...data.web,
    accent: data.web.accent as {
      light: string; dark: string; lightContrast: string; darkContrast: string;
    } | null,
  },
  provider: {
    ...data.provider,
    keyUrl: data.provider.keyUrl as string | null,
    supportQr: data.provider.supportQr as string | null,
  },
  support: { authorEmail: data.support.authorEmail as string | null },
};
`;
  writeGenerated("src/shared/brand.generated.ts", generated);
  writeGenerated("src-tauri/tauri.brand.generated.json", JSON.stringify(desktopBrandConfig(brand), null, 2) + "\n");
}

export function tauriBuildOptions(brand = readBrand()) {
  prepareBrand(brand);
  return {
    env: { ...process.env, CHATCANVAS_BRAND: brand.id, BRAND_BACKEND_PORT: String(brand.desktop.backendPort) },
    cwd: root,
    cli: path.join(root, "node_modules", "@tauri-apps", "cli", "tauri.js"),
    configPath,
  };
}

export function desktopApiEnv() {
  const brand = readBrand();
  const port = String(brand.desktop.backendPort);
  if (brand.id !== "chatcanvas" && process.env.BRAND_BACKEND_PORT !== port) {
    throw new Error("请通过 scripts/brand.mjs 或 npm 的 Tauri 命令构建独立品牌");
  }
  return { ...process.env, PORT: port, VITE_API_BASE_URL: `http://127.0.0.1:${port}` };
}

/**
 * 是否被直接当作脚本执行。
 *
 * 不能用 `path.resolve(argv[1]) === fileURLToPath(import.meta.url)`：项目目录可能是
 * 符号链接（Windows 上的 junction），此时 argv[1] 是调用路径而 import.meta.url 是真实
 * 路径，两者不等，整段 CLI 会被静默跳过——prepare 不执行，构建就用上一次的生成物。
 * 必须两边都过 realpath 再比。
 */
function invokedDirectly() {
  if (!process.argv[1]) return false;
  try {
    return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (invokedDirectly()) {
  const [command = "prepare", ...args] = process.argv.slice(2);
  if (command === "prepare") {
    prepareBrand();
  } else if (command === "port") {
    console.log(readBrand().desktop.backendPort);
  } else if (command === "changelog") {
    console.log(readBrand().desktop.updater.changelog);
  } else if (command === "tauri") {
    const [subcommand, ...tauriArgs] = args;
    if (subcommand !== "dev" && subcommand !== "build") throw new Error("请选择 tauri dev 或 tauri build");
    const { env, cwd, cli, configPath } = tauriBuildOptions();
    const result = spawnSync(process.execPath, [cli, subcommand, "--config", configPath, ...tauriArgs], { env, cwd, stdio: "inherit" });
    if (result.error) throw result.error;
    process.exitCode = result.status ?? 1;
  } else {
    throw new Error(`未知的品牌命令：${command}`);
  }
}
